export type ClockKey = Key;
export type ClockT = (key: Key, vars?: Record<string, string | number>) => string;

export function clockText(lang: string, key: Key, vars?: Record<string, string | number>) {
  const template = (lang === "ru" ? ru : en)[key] ?? ru[key];
  return vars ? template.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`)) : template;
}

export function useClockT(): ClockT {
  const lang = useLanguage();
  return (key, vars) => clockText(lang, key, vars);
}

const EN_REPEAT: RepeatLabels = { once: "Once", everyDay: "Every day", weekdays: "Weekdays", weekend: "Weekends", short: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"] };
export const repeatLabels = (lang: string) => (lang === "ru" ? RU_REPEAT : EN_REPEAT);

/** "8 ч 5 мин" / "5 мин". */
export function untilText(lang: string, parts: { hours: number; minutes: number }) {
  return parts.hours ? clockText(lang, "until.h", { h: parts.hours, m: parts.minutes }) : clockText(lang, "until.m", { m: parts.minutes });
}
